using System;
using System.Collections;
using HighCommand.Army;
using HighCommand.Orders;
using RoR2;
using UnityEngine;
using UnityEngine.Networking;

namespace HighCommand.Mode
{
    /// <summary>
    /// Identity and server brain of the High Command game mode. The Run prefab is a clone of ClassicRun (the stock Run
    /// component cannot be swapped: Run and RunArtifactManager require each other, so Unity refuses to remove either),
    /// marked by this component. Everything the mode adds lives here or in sibling components; the few places that
    /// need to differ from a classic run are Harmony patches that check <see cref="IsActive"/>.
    /// </summary>
    public class HighCommandRun : MonoBehaviour
    {
        public const string PrefabName = "HighCommandRun";
        public const string NameToken = "HIGHCOMMAND_GAMEMODE_NAME";

        /// <summary>The live run's marker, or null when no High Command run exists.</summary>
        public static HighCommandRun Instance { get; private set; }

        public static bool IsActive => Instance != null;

        /// <summary>True for a Run prefab/instance of this mode (works on the prefab in the lobby too).</summary>
        public static bool IsModeRun(Run run) => run && run.GetComponent<HighCommandRun>();

        /// <summary>The roster. Filled on the server only.</summary>
        public ArmyManager Army { get; } = new ArmyManager();

        private bool subscribed;

        private HcState state;

        /// <summary>The replicated state (gold, roster, prices) that lives on the same object.</summary>
        public HcState State => state ? state : (state = GetComponent<HcState>());

        /// <summary>Server: where reinforcements land and where retreating heroes run to.</summary>
        public Vector3 RallyPoint { get; set; }

        /// <summary>Server: hands the pool's items out to the heroes.</summary>
        internal ItemDistributor Items { get; } = new ItemDistributor();

        /// <summary>Server: the item pool changed (an item was gained). Triggers redistribution among heroes.</summary>
        public void OnPoolChanged()
        {
            try { Items.Sync(Army); }
            catch (Exception e) { Plugin.Log.LogError("Item distribution failed: " + e); }
            PublishRoster(); // spare equipment travels with the roster
            PoolChanged?.Invoke();
        }

        public event System.Action PoolChanged;

        /// <summary>Server: sends the current roster to the clients.</summary>
        public void PublishRoster()
        {
            if (NetworkServer.active && State != null) State.ServerPublishRoster(Army);
        }

        private void OnEnable()
        {
            Instance = this;
            Plugin.Log.LogInfo($"High Command run started (server={NetworkServer.active}).");

            if (NetworkServer.active && !subscribed)
            {
                Stage.onServerStageBegin += OnServerStageBegin;
                subscribed = true;
                Economy.ResetForNewRun();
            }
            if (NetworkClient.active) CreateClientSide();
        }

        private void OnDisable()
        {
            DestroyClientSide();
            if (subscribed)
            {
                Stage.onServerStageBegin -= OnServerStageBegin;
                subscribed = false;
            }
            if (Instance == this) Instance = null;
            Army.Clear();
            Items.Reset();
        }

        // ---- server: stage flow --------------------------------------------------------------------

        private void OnServerStageBegin(Stage stage)
        {
            try
            {
                if (Army.Count == 0)
                    StartCoroutine(SpawnStartingArmy(stage));
            }
            catch (Exception e)
            {
                Plugin.Log.LogError("OnServerStageBegin failed: " + e);
            }
        }

        /// <summary>
        /// The commander (the player master, which never gets a body) carries the survivor and loadout chosen in the
        /// lobby. They become the first soldier, who drops in with the pod like a normal player would.
        /// </summary>
        private IEnumerator SpawnStartingArmy(Stage stage)
        {
            // Spawn points are generated by the scene director on its own schedule: give it a moment.
            float waited = 0f;
            while (SpawnPoint.readOnlyInstancesList.Count == 0 && waited < 5f)
            {
                waited += Time.unscaledDeltaTime;
                yield return null;
            }
            if (!stage || Army.Count > 0) yield break;

            var commanders = PlayerCharacterMasterController.instances;
            if (commanders.Count == 0) Plugin.Log.LogWarning("No commander (player master) found; starting with the default survivor.");

            int created = 0;
            for (int i = 0; i < Math.Max(1, commanders.Count); i++)
            {
                CharacterMaster commander = i < commanders.Count ? commanders[i].master : null;
                SurvivorDef survivor = null;
                if (commander && commander.bodyPrefab)
                    survivor = SurvivorCatalog.FindSurvivorDefFromBody(commander.bodyPrefab);
                if (!survivor) survivor = SurvivorCatalog.defaultSurvivor;
                if (!survivor) { Plugin.Log.LogError("No survivor to start the army with."); continue; }

                Vector3 position = Vector3.zero;
                Quaternion rotation = Quaternion.identity;
                Transform spawn = stage.GetPlayerSpawnTransform();
                if (spawn) { position = spawn.position; rotation = spawn.rotation; }
                if (created == 0) RallyPoint = Formation.SnapToGround(position);

                Loadout loadout = commander ? commander.loadout : null;
                bool pod = stage.usePod && Run.instance && Run.instance.spawnWithPod;
                if (RecruitHero(survivor, loadout, position, rotation, pod) != null) created++;
            }
            PublishRoster();
            Plugin.Log.LogInfo($"Starting army created: {created} hero(es).");
        }

        /// <summary>Server: creates a hero and, when it arrives in a pod, makes sure the pod opens for it.</summary>
        public Hero RecruitHero(SurvivorDef survivor, Loadout loadout, Vector3 position, Quaternion rotation, bool withPod)
        {
            Hero hero = Army.Recruit(survivor, loadout, position, rotation, withPod);
            if (hero == null) return null;

            if (withPod) StartCoroutine(OpenPodWhenLanded(hero));
            try
            {
                Items.CatchUp(Army, hero);
                Items.Sync(Army);
            }
            catch (Exception e) { Plugin.Log.LogError("Item catch-up failed: " + e); }
            return hero;
        }

        // A player opens the pod with the interact key. The AI passenger has no key: ask the pod to let it out once
        // it has landed (the seat only allows the exit then).
        private IEnumerator OpenPodWhenLanded(Hero hero)
        {
            float timeout = 40f;
            while (timeout > 0f && hero != null && hero.Exists)
            {
                timeout -= 0.5f;
                yield return new WaitForSeconds(0.5f);

                CharacterBody body = hero.Body;
                if (!body) continue;
                VehicleSeat seat = body.currentVehicle;
                if (!seat) { if (timeout < 38f) yield break; else continue; }
                Interactor interactor = body.GetComponent<Interactor>();
                if (interactor) interactor.AttemptInteraction(seat.gameObject);
            }
        }

        // ---- client side -----------------------------------------------------------------------------

        private GameObject clientRoot;

        private void CreateClientSide()
        {
            if (clientRoot) return;
            clientRoot = new GameObject("HighCommand.Client");
            DontDestroyOnLoad(clientRoot);
            try
            {
                clientRoot.AddComponent<Client.ClientRoot>();
            }
            catch (Exception e)
            {
                Plugin.Log.LogError("Client side failed to start: " + e);
            }
        }

        private void DestroyClientSide()
        {
            if (clientRoot) Destroy(clientRoot);
            clientRoot = null;
        }
    }
}
